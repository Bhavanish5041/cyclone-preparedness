def build_priority_explanation(row: Union[pd.Series, Dict[str, Any]]) -> str:
    """Generate transparent textual synthesis explaining priority factors for an administrative unit."""
    tier = str(row.get("preparedness_tier", "Unknown")).strip().capitalize()
    score = round(float(row.get("preparedness_score", 0.0)), 2)
    band = str(row.get("priority_band", "BAND_3_MODERATE"))
    assignment_status = str(row.get("cluster_assignment_status", "")).strip()
    is_assigned = assignment_status == "ASSIGNED"

    parts = [f"Unit assigned to {band} with Deterministic AHP Preparedness Score of {score} ({tier} tier)."]

    # Explain triggers
    dist_coast = float(row.get("dist_coast_km", 99.0))
    score_shelter = float(row.get("score_shelters", 50.0))
    score_med = float(row.get("score_medical", 50.0))

    triggers_met = []
    if dist_coast < COASTAL_PROXIMITY_THRESHOLD_KM:
        triggers_met.append(f"coastal proximity ({dist_coast:.1f} km < 5 km)")
    if score_shelter < SHELTER_DEFICIT_THRESHOLD:
        triggers_met.append(f"shelter capacity deficit (score {score_shelter:.1f} < 20)")
    if score_med < MEDICAL_DEFICIT_THRESHOLD:
        triggers_met.append(f"medical remoteness (score {score_med:.1f} < 35)")

    if triggers_met:
        parts.append("Triggered sector vulnerabilities: " + "; ".join(triggers_met) + ".")
    else:
        parts.append("No acute sector threshold triggers (coastal proximity, acute shelter or medical deficit) met.")

    # Archetype Context
    if is_assigned:
        raw_arch_id = row.get("vulnerability_archetype_id")
        arch_label = str(row.get("vulnerability_archetype_label", "N/A"))
        parts.append(
            f"Archetype Context (Descriptive Background): Assigned to Cluster {raw_arch_id} ({arch_label}). "
            "Cluster traits provide contextual background and do not imply unverified individual deficiencies."
        )
    else:
        parts.append(
            "Spatial Coverage Notice: Unassigned to K-Means clustering (coverage limited to Dakshina Kannada & Udupi). "
            "Evaluated strictly via AHP domain scores and physical infrastructure indicators."
        )

    # Model agreement note
    agreement = str(row.get("model_agreement_status", "FULL_AGREEMENT"))
    pred_tier = str(row.get("predicted_preparedness_tier", tier)).strip().capitalize()
    margin = round(float(row.get("probability_margin", 1.0)), 4)
    if agreement == "BORDERLINE_DISAGREEMENT":
        parts.append(
            f"Model Sensitivity Flag: Logistic Regression predicted '{pred_tier}' (margin: {margin:.4f}). "
            "Deterministic AHP baseline tier is preserved for operational governance."
        )

    return " ".join(parts)


def build_unit_evaluation(row: Union[pd.Series, Dict[str, Any]]) -> DecisionSupportEvaluation:
    """Build complete DecisionSupportEvaluation Pydantic model for a single unit row."""
    # Ensure raw values convert cleanly
    shrid2 = str(row["shrid2"])
    pc11_id = str(row.get("pc11_id", ""))
    village_name = str(row.get("village_name", ""))
    district_name = str(row.get("district_name", ""))
    subdistrict_name = str(row.get("subdistrict_name", ""))

    raw_ut = row.get("unit_type")
    unit_type = str(raw_ut) if (raw_ut is not None and str(raw_ut).strip() and str(raw_ut).lower() != "nan") else None

    lat = float(row.get("lat", 0.0))
    lon = float(row.get("lon", 0.0))

    prep_score = round(float(row["preparedness_score"]), 4)
    prep_tier = str(row["preparedness_tier"]).strip().capitalize()

    domain_scores = {
        "score_medical": round(float(row.get("score_medical", 0.0)), 4),
        "score_shelters": round(float(row.get("score_shelters", 0.0)), 4),
        "score_infrastructure": round(float(row.get("score_infrastructure", 0.0)), 4),
        "score_early_warning": round(float(row.get("score_early_warning", 0.0)), 4),
        "score_socioeconomic": round(float(row.get("score_socioeconomic", 0.0)), 4),
    }

    pred_tier = str(row.get("predicted_preparedness_tier", prep_tier)).strip().capitalize()
    class_probs = {
        "prob_low": round(float(row.get("prob_low", 0.0)), 4),
        "prob_medium": round(float(row.get("prob_medium", 0.0)), 4),
        "prob_high": round(float(row.get("prob_high", 0.0)), 4),
    }

    max_prob = round(float(row.get("max_class_probability", max(class_probs.values()))), 4)
    prob_margin = round(float(row.get("probability_margin", 1.0)), 4)
    provenance = str(row.get("prediction_provenance", "UNKNOWN"))
    agreement_status = str(row.get("model_agreement_status", "FULL_AGREEMENT"))
    is_boundary = bool(row.get("is_boundary_case", (prob_margin < 0.10 or max_prob < 0.60)))

    # Archetype fields
    raw_arch_id = row.get("vulnerability_archetype_id")
    archetype_id = int(raw_arch_id) if (raw_arch_id is not None and not pd.isna(raw_arch_id)) else None
    raw_arch_lbl = row.get("vulnerability_archetype_label")
    archetype_label = str(raw_arch_lbl) if (raw_arch_lbl is not None and not pd.isna(raw_arch_lbl)) else None
    cluster_status = str(row.get("cluster_assignment_status", "UNASSIGNED_OUT_OF_STUDY_AREA"))

    # Priority outputs
    priority_band = str(row.get("priority_band", "BAND_3_MODERATE"))
    band_rank = int(row.get("band_rank", 1))
    overall_priority_rank = int(row.get("overall_priority_rank", 1))

    priority_explanation = build_priority_explanation(row)
    advisories = evaluate_unit_advisories(row)

    has_unverified = any(a.directive_id == "ADV_DATA_INCOMPLETE" for a in advisories)

    return DecisionSupportEvaluation(
        shrid2=shrid2,
        pc11_id=pc11_id,
        village_name=village_name,
        district_name=district_name,
        subdistrict_name=subdistrict_name,
        unit_type=unit_type,
        lat=lat,
        lon=lon,
        preparedness_score=prep_score,
        preparedness_tier=prep_tier,
        domain_scores=domain_scores,
        predicted_preparedness_tier=pred_tier,
        class_probabilities=class_probs,
        max_class_probability=max_prob,
        probability_margin=prob_margin,
        prediction_provenance=provenance,
        model_agreement_status=agreement_status,
        is_boundary_case=is_boundary,
        vulnerability_archetype_id=archetype_id,
        vulnerability_archetype_label=archetype_label,
        cluster_assignment_status=cluster_status,
        provisional_priority_band=priority_band,
        band_rank=band_rank,
        overall_priority_rank=overall_priority_rank,
        priority_explanation=priority_explanation,
        recommended_advisories=advisories,
        has_unverified_indicators=has_unverified,
        advisory_disclaimer=DECISION_SUPPORT_DISCLAIMER,
    )


def get_regional_decision_summary(df: pd.DataFrame) -> RegionalDecisionSummaryResponse:
    """Compute regional aggregation across all 1,879 records."""
    total_units = len(df)

    # Band counts
    band_counts = df["priority_band"].value_counts().to_dict()

    # District by band breakdown
    dist_band_ct = pd.crosstab(df["district_name"], df["priority_band"]).to_dict(orient="index")
    district_band_breakdown = {str(k): {str(bk): int(bv) for bk, bv in v.items()} for k, v in dist_band_ct.items()}

    # Model agreement counts
    agreement_counts = df["model_agreement_status"].value_counts().to_dict()
    model_agreement_dict = {str(k): int(v) for k, v in agreement_counts.items()}

    # Model agreement by split provenance (in-sample training vs out-of-sample validation/test)
    provenance_agreement = {}
    if "prediction_provenance" in df.columns and "predicted_preparedness_tier" in df.columns:
        tier_clean = df["preparedness_tier"].astype(str).str.strip().str.capitalize()
        pred_clean = df["predicted_preparedness_tier"].astype(str).str.strip().str.capitalize()
        for prov in ["TRAIN_IN_SAMPLE", "VAL_OUT_OF_SAMPLE", "TEST_OUT_OF_SAMPLE"]:
            sub = df[df["prediction_provenance"] == prov]
            if len(sub) > 0:
                sub_agree = int((tier_clean.loc[sub.index] == pred_clean.loc[sub.index]).sum())
                provenance_agreement[prov] = {
                    "total": int(len(sub)),
                    "agreement": sub_agree,
                    "disagreement": int(len(sub) - sub_agree),
                    "agreement_rate": round(float(sub_agree / len(sub)), 4),
                }

    # UK trigger breakdown
    uk = df[df["cluster_assignment_status"] == "UNASSIGNED_OUT_OF_STUDY_AREA"]
    t_coast = (uk["dist_coast_km"] < COASTAL_PROXIMITY_THRESHOLD_KM).sum()
    t_shelter = (uk["score_shelters"] < SHELTER_DEFICIT_THRESHOLD).sum()
    t_medical = (uk["score_medical"] < MEDICAL_DEFICIT_THRESHOLD).sum()
    t_low = (uk["preparedness_score"] < AHP_LOW_THRESHOLD).sum()

    sec_trig_series = (
        (uk["dist_coast_km"] < COASTAL_PROXIMITY_THRESHOLD_KM).astype(int)
        + (uk["score_shelters"] < SHELTER_DEFICIT_THRESHOLD).astype(int)
        + (uk["score_medical"] < MEDICAL_DEFICIT_THRESHOLD).astype(int)
    )
    t_zero_routine = ((sec_trig_series == 0) & (uk["preparedness_score"] >= AHP_LOW_THRESHOLD)).sum()
    t_zero_low = ((sec_trig_series == 0) & (uk["preparedness_score"] < AHP_LOW_THRESHOLD)).sum()

    uk_trigger_dict = {
        "coastal_proximity_count": int(t_coast),
        "shelter_deficit_count": int(t_shelter),
        "medical_remoteness_count": int(t_medical),
        "baseline_low_tier_count": int(t_low),
        "zero_sector_triggers_routine_count": int(t_zero_routine),
        "zero_sector_triggers_general_low_count": int(t_zero_low),
        "total_unassigned_units": len(uk),
    }

    return RegionalDecisionSummaryResponse(
        total_units=total_units,
        band_counts={str(k): int(v) for k, v in band_counts.items()},
        district_band_breakdown=district_band_breakdown,
        model_agreement_counts=model_agreement_dict,
        provenance_agreement=provenance_agreement,
        uttara_kannada_trigger_breakdown=uk_trigger_dict,
        methodological_disclaimer=DECISION_SUPPORT_DISCLAIMER,
    )
