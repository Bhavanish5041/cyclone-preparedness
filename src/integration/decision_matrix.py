"""Decision support rule evaluation engine.

Implements the finalized Milestone 3A/3B architecture combining:
1. Deterministic AHP Preparedness baseline (preparedness_score, preparedness_tier, 5 domain scores).
2. Multinomial Logistic Regression model stability outputs (predicted tier, uncalibrated class probabilities, margin, provenance).
3. K-Means Vulnerability Archetypes for assigned units (Dakshina Kannada & Udupi, N=622).
4. Independent multi-trigger domain-deficit fallback engine for unassigned units (Uttara Kannada, N=1,257).

Produces evidence-grounded advisory recommendations, priority bands, and deterministic null-safe rankings.
"""

